//! Multi-Factor Authentication HTTP handlers.
//!
//! * `POST /api/v1/mfa/setup` - initiate TOTP configuration
//! * `POST /api/v1/mfa/enable` - confirm first TOTP code and obtain backup codes
//! * `POST /api/v1/mfa/disable` - disable MFA using account password

use axum::Json;
use axum::extract::State;
use serde::{Deserialize, Serialize};
use utoipa::ToSchema;

use super::auth::MessageResponse;
use crate::adapters::inbound::http::error::{ApiError, ProblemDetails};
use crate::adapters::inbound::http::extractors::{AuthUser, ClientMetadata, StepUpUser};
use crate::adapters::inbound::http::state::AppState;
use crate::application::dto::{DisableTotpCommand, EnableTotpCommand, SetupTotpCommand};

/// TOTP setup response payload.
#[derive(Clone, Serialize, ToSchema)]
pub struct TotpSetupResponse {
    /// Base32 secret for manual entry into authenticator app.
    #[schema(example = "JBSWY3DPEHPK3PXP")]
    pub secret: String,

    /// Inline SVG QR code image string.
    #[schema(example = "<svg xmlns=\"http://www.w3.org/2000/svg\"...")]
    pub qr_code_svg: String,
}

impl std::fmt::Debug for TotpSetupResponse {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("TotpSetupResponse")
            .field("secret", &"[REDACTED]")
            .field("qr_code_svg", &"[REDACTED]")
            .finish()
    }
}

/// Enable TOTP request payload.
#[derive(Clone, Deserialize, ToSchema)]
pub struct EnableTotpRequest {
    /// 6-digit TOTP code generated by authenticator app.
    #[schema(example = "123456")]
    pub code: String,
}

impl std::fmt::Debug for EnableTotpRequest {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("EnableTotpRequest")
            .field("code", &"[REDACTED]")
            .finish()
    }
}

/// Enable TOTP response payload returning single-use backup codes.
#[derive(Clone, Serialize, ToSchema)]
pub struct TotpEnabledResponse {
    /// 10 single-use plaintext backup codes. Save these in a secure place.
    #[schema(example = json!(["a1b2c3d4", "e5f6g7h8"]))]
    pub backup_codes: Vec<String>,
}

impl std::fmt::Debug for TotpEnabledResponse {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("TotpEnabledResponse")
            .field("backup_codes", &"[REDACTED]")
            .finish()
    }
}

/// Disable TOTP request payload.
#[derive(Clone, Deserialize, ToSchema)]
pub struct DisableTotpRequest {
    /// Current account plaintext password.
    #[schema(example = "CurrentP@ssword123!")]
    pub current_password: String,
}

impl std::fmt::Debug for DisableTotpRequest {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("DisableTotpRequest")
            .field("current_password", &"[REDACTED]")
            .finish()
    }
}

/// Initiates TOTP setup, generating a new secret and QR code.
#[utoipa::path(
    post,
    path = "/api/v1/mfa/setup",
    tag = "MFA",
    operation_id = "mfa_setup",
    security(("BearerAuth" = [])),
    responses(
        (status = 200, description = "TOTP setup initiated", body = TotpSetupResponse),
        (status = 401, description = "Unauthenticated", body = ProblemDetails),
        (status = 429, description = "Rate limit exceeded", body = ProblemDetails),
        (status = 500, description = "Unexpected server error", body = ProblemDetails)
    )
)]
pub async fn setup(
    State(state): State<AppState>,
    auth_user: AuthUser,
    metadata: ClientMetadata,
) -> Result<Json<TotpSetupResponse>, ApiError> {
    let cmd = SetupTotpCommand {
        user_id: auth_user.user_id,
        request_id: metadata.request_id,
    };

    let result = state.setup_totp_use_case.execute(cmd).await?;

    Ok(Json(TotpSetupResponse {
        secret: result.secret,
        qr_code_svg: result.qr_code_svg,
    }))
}

/// Verifies first TOTP code and finalizes enabling MFA.
#[utoipa::path(
    post,
    path = "/api/v1/mfa/enable",
    tag = "MFA",
    operation_id = "mfa_enable",
    security(("BearerAuth" = [])),
    request_body = EnableTotpRequest,
    responses(
        (status = 200, description = "MFA enabled; backup codes returned", body = TotpEnabledResponse),
        (status = 401, description = "Invalid verification code or setup expired", body = ProblemDetails),
        (status = 422, description = "Validation failed", body = ProblemDetails),
        (status = 429, description = "Rate limit exceeded", body = ProblemDetails),
        (status = 500, description = "Unexpected server error", body = ProblemDetails)
    )
)]
pub async fn enable(
    State(state): State<AppState>,
    auth_user: AuthUser,
    metadata: ClientMetadata,
    Json(body): Json<EnableTotpRequest>,
) -> Result<Json<TotpEnabledResponse>, ApiError> {
    let cmd = EnableTotpCommand {
        user_id: auth_user.user_id,
        code: body.code,
        ip_address: Some(metadata.ip),
        user_agent: metadata.user_agent,
        request_id: metadata.request_id,
    };

    let result = state.enable_totp_use_case.execute(cmd).await?;

    Ok(Json(TotpEnabledResponse {
        backup_codes: result.backup_codes,
    }))
}

/// Disables MFA on the authenticated caller's account after confirming password.
#[utoipa::path(
    post,
    path = "/api/v1/mfa/disable",
    tag = "MFA",
    operation_id = "mfa_disable",
    security(("BearerAuth" = [])),
    request_body = DisableTotpRequest,
    responses(
        (status = 200, description = "MFA disabled", body = MessageResponse),
        (status = 401, description = "Invalid credentials or unauthenticated", body = ProblemDetails),
        (status = 403, description = "Step-up authentication required", body = ProblemDetails),
        (status = 422, description = "Validation failed", body = ProblemDetails),
        (status = 429, description = "Rate limit exceeded", body = ProblemDetails),
        (status = 500, description = "Unexpected server error", body = ProblemDetails)
    )
)]
pub async fn disable(
    State(state): State<AppState>,
    auth_user: StepUpUser,
    metadata: ClientMetadata,
    Json(body): Json<DisableTotpRequest>,
) -> Result<Json<MessageResponse>, ApiError> {
    let cmd = DisableTotpCommand {
        user_id: auth_user.user_id,
        current_password: body.current_password,
        ip_address: Some(metadata.ip),
        user_agent: metadata.user_agent,
        request_id: metadata.request_id,
    };

    state.disable_totp_use_case.execute(cmd).await?;

    Ok(Json(MessageResponse::new(
        "Multi-Factor Authentication has been successfully disabled.",
    )))
}
