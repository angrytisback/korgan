//! Strongly-typed, time-ordered identifiers (RFC 9562 UUIDv7).
//!
//! Every identifier is a newtype so that, for example, a [`SessionId`] can never
//! be passed where a [`UserId`] is expected.
//!
//! Creation (`new()`) always enforces UUIDv7 generation.
//! Parsing (`from_uuid()`, `TryFrom<Uuid>`, `FromStr`, serde) validates that the
//! UUID is a valid, non-nil identifier, allowing existing valid UUIDs to be parsed.

use std::fmt;
use std::str::FromStr;

use serde::{Deserialize, Serialize};
use uuid::{Uuid, Version};

use crate::domain::errors::DomainError;

macro_rules! uuid_id {
    ($(#[$meta:meta])* $name:ident, $kind:literal) => {
        $(#[$meta])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
        #[serde(try_from = "Uuid", into = "Uuid")]
        pub struct $name(Uuid);

        impl $name {
            /// Generates a fresh, time-ordered UUIDv7 identifier.
            #[must_use]
            pub fn new() -> Self {
                Self(Uuid::now_v7())
            }

            /// Creates an identifier from an existing [`Uuid`], validating that it is not nil.
            pub fn from_uuid(value: Uuid) -> Result<Self, DomainError> {
                Self::try_from(value)
            }

            /// Returns the underlying [`Uuid`].
            #[must_use]
            pub const fn as_uuid(&self) -> Uuid {
                self.0
            }

            /// Returns the underlying [`Uuid`].
            #[must_use]
            pub const fn to_uuid(&self) -> Uuid {
                self.0
            }

            /// Returns the 16-byte array representation of the underlying [`Uuid`].
            #[must_use]
            pub const fn as_bytes(&self) -> &[u8; 16] {
                self.0.as_bytes()
            }

            /// Returns true if the underlying UUID has RFC 9562 Version 7 format.
            #[must_use]
            pub fn is_v7(&self) -> bool {
                self.0.get_version() == Some(Version::SortRand)
            }
        }

        impl Default for $name {
            fn default() -> Self {
                Self::new()
            }
        }

        impl TryFrom<Uuid> for $name {
            type Error = DomainError;

            fn try_from(value: Uuid) -> Result<Self, Self::Error> {
                if value.is_nil() {
                    Err(DomainError::InvalidIdentifier { kind: $kind })
                } else {
                    Ok(Self(value))
                }
            }
        }

        impl From<$name> for Uuid {
            fn from(value: $name) -> Self {
                value.0
            }
        }

        impl FromStr for $name {
            type Err = DomainError;

            fn from_str(s: &str) -> Result<Self, Self::Err> {
                let parsed = Uuid::parse_str(s)
                    .map_err(|_| DomainError::InvalidIdentifier { kind: $kind })?;
                Self::try_from(parsed)
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                fmt::Display::fmt(&self.0.hyphenated(), f)
            }
        }
    };
}

uuid_id!(
    /// Primary key of a user account.
    UserId,
    "user_id"
);
uuid_id!(
    /// Primary key of a session; embedded as the `sid` claim of access tokens.
    SessionId,
    "session_id"
);
uuid_id!(
    /// Groups rotated refresh tokens so that reuse can revoke the whole family.
    TokenFamilyId,
    "token_family_id"
);
uuid_id!(
    /// Primary key of an immutable audit log record.
    AuditLogId,
    "audit_log_id"
);
uuid_id!(
    /// Primary key of an external OAuth account link.
    OAuthAccountId,
    "oauth_account_id"
);
uuid_id!(
    /// Primary key of a WebAuthn / FIDO2 Passkey credential.
    PasskeyId,
    "passkey_id"
);

/// Correlation identifier attached to every request, log line and RFC 9457
/// error `instance`.
///
/// Identifiers generated by this service are always UUIDv7. A caller-supplied
/// `X-Request-Id` is accepted when it is any valid, non-nil UUID so that
/// existing upstream correlation IDs are preserved end-to-end.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(try_from = "Uuid", into = "Uuid")]
pub struct RequestId(Uuid);

impl RequestId {
    /// Generates a fresh UUIDv7 request identifier.
    #[must_use]
    pub fn new() -> Self {
        Self(Uuid::now_v7())
    }

    /// Creates an identifier from an existing [`Uuid`], validating that it is not nil.
    pub fn from_uuid(value: Uuid) -> Result<Self, DomainError> {
        Self::try_from(value)
    }

    /// Returns the underlying [`Uuid`].
    #[must_use]
    pub const fn as_uuid(&self) -> Uuid {
        self.0
    }

    /// Returns the underlying [`Uuid`].
    #[must_use]
    pub const fn to_uuid(&self) -> Uuid {
        self.0
    }

    /// Returns the RFC 9457 `instance` URI (`urn:uuid:<request_id>`).
    #[must_use]
    pub fn as_instance_urn(&self) -> String {
        format!("urn:uuid:{}", self.0.hyphenated())
    }
}

impl Default for RequestId {
    fn default() -> Self {
        Self::new()
    }
}

impl TryFrom<Uuid> for RequestId {
    type Error = DomainError;

    fn try_from(value: Uuid) -> Result<Self, Self::Error> {
        if value.is_nil() {
            Err(DomainError::InvalidIdentifier { kind: "request_id" })
        } else {
            Ok(Self(value))
        }
    }
}

impl From<RequestId> for Uuid {
    fn from(value: RequestId) -> Self {
        value.0
    }
}

impl FromStr for RequestId {
    type Err = DomainError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let parsed = Uuid::parse_str(s)
            .map_err(|_| DomainError::InvalidIdentifier { kind: "request_id" })?;
        Self::try_from(parsed)
    }
}

impl fmt::Display for RequestId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        fmt::Display::fmt(&self.0.hyphenated(), f)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    type TestResult = Result<(), Box<dyn std::error::Error>>;

    #[test]
    fn generated_ids_are_uuid_v7() {
        let user_id = UserId::new();
        let session_id = SessionId::new();
        let token_family_id = TokenFamilyId::new();
        let audit_id = AuditLogId::new();
        let req_id = RequestId::new();

        assert_eq!(user_id.as_uuid().get_version(), Some(Version::SortRand));
        assert!(user_id.is_v7());
        assert_eq!(session_id.as_uuid().get_version(), Some(Version::SortRand));
        assert!(session_id.is_v7());
        assert_eq!(
            token_family_id.as_uuid().get_version(),
            Some(Version::SortRand)
        );
        assert!(token_family_id.is_v7());
        assert_eq!(audit_id.as_uuid().get_version(), Some(Version::SortRand));
        assert!(audit_id.is_v7());
        assert_eq!(req_id.as_uuid().get_version(), Some(Version::SortRand));
    }

    #[test]
    fn ids_are_time_ordered() {
        let first = UserId::new();
        std::thread::sleep(std::time::Duration::from_millis(2));
        let second = UserId::new();
        assert!(first < second);
    }

    #[test]
    fn allows_parsing_existing_valid_uuid() -> TestResult {
        let v4 = Uuid::new_v4();
        let user_id = UserId::try_from(v4)?;
        assert_eq!(user_id.as_uuid(), v4);
        assert!(!user_id.is_v7());

        let parsed: UserId = v4.to_string().parse()?;
        assert_eq!(parsed.as_uuid(), v4);

        let parsed_session: SessionId = v4.to_string().parse()?;
        assert_eq!(parsed_session.as_uuid(), v4);

        let parsed_family: TokenFamilyId = v4.to_string().parse()?;
        assert_eq!(parsed_family.as_uuid(), v4);
        Ok(())
    }

    #[test]
    fn rejects_nil_uuid() {
        assert_eq!(
            UserId::try_from(Uuid::nil()),
            Err(DomainError::InvalidIdentifier { kind: "user_id" })
        );
        assert_eq!(
            SessionId::try_from(Uuid::nil()),
            Err(DomainError::InvalidIdentifier { kind: "session_id" })
        );
        assert_eq!(
            TokenFamilyId::try_from(Uuid::nil()),
            Err(DomainError::InvalidIdentifier {
                kind: "token_family_id"
            })
        );
        assert_eq!(
            AuditLogId::try_from(Uuid::nil()),
            Err(DomainError::InvalidIdentifier {
                kind: "audit_log_id"
            })
        );
        assert_eq!(
            RequestId::try_from(Uuid::nil()),
            Err(DomainError::InvalidIdentifier { kind: "request_id" })
        );
    }

    #[test]
    fn round_trips_through_string() -> TestResult {
        let id = SessionId::new();
        let parsed: SessionId = id.to_string().parse()?;
        assert_eq!(id, parsed);
        Ok(())
    }

    #[test]
    fn instance_urn_has_expected_shape() {
        let id = RequestId::new();
        assert_eq!(id.as_instance_urn(), format!("urn:uuid:{id}"));
    }

    #[test]
    fn serde_round_trips_valid_uuid() -> TestResult {
        let id = UserId::new();
        let json = serde_json::to_string(&id)?;
        let back: UserId = serde_json::from_str(&json)?;
        assert_eq!(id, back);

        let nil_json = serde_json::to_string(&Uuid::nil())?;
        assert!(serde_json::from_str::<UserId>(&nil_json).is_err());
        Ok(())
    }
}
