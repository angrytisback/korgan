//! Multi-Factor Authentication DTO commands and results.

use std::net::IpAddr;

use serde::{Deserialize, Serialize};
use validator::Validate;

use crate::domain::value_objects::{RequestId, UserId};

/// Command to initiate TOTP setup.
#[derive(Debug, Clone, Validate)]
pub struct SetupTotpCommand {
    /// Authenticated user identifier.
    pub user_id: UserId,

    /// Correlation request identifier.
    pub request_id: RequestId,
}

/// Result of TOTP setup containing the secret and QR code.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TotpSetupResult {
    /// Base32-encoded TOTP secret for manual entry.
    pub secret: String,

    /// Inline SVG QR code image string.
    pub qr_code_svg: String,
}

impl std::fmt::Debug for TotpSetupResult {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("TotpSetupResult")
            .field("secret", &"[REDACTED]")
            .field("qr_code_svg", &"[REDACTED]")
            .finish()
    }
}

/// Command to verify first TOTP code and finalize enabling MFA.
#[derive(Clone, Validate)]
pub struct EnableTotpCommand {
    /// Authenticated user identifier.
    pub user_id: UserId,

    /// 6-digit verification code generated by the authenticator app.
    #[validate(length(equal = 6, message = "code must be exactly 6 digits"))]
    pub code: String,

    /// Client IP address.
    pub ip_address: Option<IpAddr>,

    /// Client User-Agent header.
    pub user_agent: Option<String>,

    /// Correlation request identifier.
    pub request_id: RequestId,
}

impl std::fmt::Debug for EnableTotpCommand {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("EnableTotpCommand")
            .field("user_id", &self.user_id)
            .field("code", &"[REDACTED]")
            .field("ip_address", &self.ip_address)
            .field("user_agent", &self.user_agent)
            .field("request_id", &self.request_id)
            .finish()
    }
}

/// Result returned when MFA is successfully enabled, showing backup codes ONCE.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct TotpEnabledResult {
    /// 10 single-use plaintext backup codes.
    pub backup_codes: Vec<String>,
}

impl std::fmt::Debug for TotpEnabledResult {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("TotpEnabledResult")
            .field("backup_codes", &"[REDACTED]")
            .finish()
    }
}

/// Command to disable MFA on an account.
#[derive(Clone, Validate)]
pub struct DisableTotpCommand {
    /// Authenticated user identifier.
    pub user_id: UserId,

    /// Current plaintext password to confirm destructive action.
    #[validate(length(min = 1, message = "password must not be empty"))]
    pub current_password: String,

    /// Client IP address.
    pub ip_address: Option<IpAddr>,

    /// Client User-Agent header.
    pub user_agent: Option<String>,

    /// Correlation request identifier.
    pub request_id: RequestId,
}

impl std::fmt::Debug for DisableTotpCommand {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("DisableTotpCommand")
            .field("user_id", &self.user_id)
            .field("current_password", &"[REDACTED]")
            .field("ip_address", &self.ip_address)
            .field("user_agent", &self.user_agent)
            .field("request_id", &self.request_id)
            .finish()
    }
}

