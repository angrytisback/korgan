-- 0002_users_and_passwords.sql
CREATE TABLE users (
    id UUID PRIMARY KEY, -- Must be UUIDv7 generated by application
    email CITEXT NOT NULL UNIQUE,
    username CITEXT UNIQUE,
    password_hash TEXT NOT NULL,
    status account_status NOT NULL DEFAULT 'unverified',
    email_verified_at TIMESTAMPTZ,
    mfa_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    failed_login_attempts SMALLINT NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    deletion_scheduled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_users_status_deletion ON users (status, deletion_scheduled_at)
    WHERE status = 'pending_deletion';

CREATE TABLE password_history (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_password_history_user_created ON password_history (user_id, created_at DESC);
